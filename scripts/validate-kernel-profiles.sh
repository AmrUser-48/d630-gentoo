#!/bin/sh
set -eu
modular=kernels/profiles/20-d630-base.config
tiny=kernels/profiles/30-d630-live.config
builtin=kernels/profiles/40-d630-builtin.config
for file in "$modular" "$tiny" "$builtin"; do
    test -s "$file" || { echo "Missing kernel profile: $file" >&2; exit 1; }
    if grep -q '^CONFIG_MCORE2=' "$file"; then
        echo "CONFIG_MCORE2 is not a valid x86-64 processor-family setting: $file" >&2
        exit 1
    fi
    duplicates="$(awk -F= '/^CONFIG_[A-Za-z0-9_]+=/{if (seen[$1]++) print $1}' "$file")"
    if [ -n "$duplicates" ]; then
        echo "Duplicate Kconfig assignments in $file:" >&2
        printf '%s\n' "$duplicates" >&2
        exit 1
    fi
done
require() {
    file=$1 key=$2 value=$3
    grep -Fxq "$key=$value" "$file" || { echo "Expected $file to contain $key=$value" >&2; exit 1; }
}

# Every D630 kernel keeps ext4 built in; it is never a module.
for file in "$modular" "$tiny" "$builtin"; do
    require "$file" CONFIG_EXT4_FS y
    require "$file" CONFIG_NTFS3_FS y
done

# Profile 20: modular installed Gentoo kernel. Use the Debian D630 module
# inventory as the pruning reference; keep hardware drivers modular where safe.
for key in CONFIG_64BIT CONFIG_X86_64 CONFIG_SMP CONFIG_CPU_SUP_INTEL CONFIG_X86_MSR CONFIG_X86_CPUID CONFIG_PROC_FS CONFIG_IKCONFIG CONFIG_IKCONFIG_PROC CONFIG_MICROCODE CONFIG_FW_LOADER CONFIG_MODULE_COMPRESS CONFIG_MODULE_COMPRESS_ZSTD CONFIG_MODULES CONFIG_MODULE_UNLOAD CONFIG_BLK_DEV_INITRD CONFIG_DEVTMPFS CONFIG_TMPFS CONFIG_ATA CONFIG_SATA_AHCI CONFIG_SCSI CONFIG_BLK_DEV_SD CONFIG_AGP CONFIG_DRM_FBDEV_EMULATION CONFIG_FB CONFIG_VGA_CONSOLE CONFIG_FRAMEBUFFER_CONSOLE CONFIG_WLAN CONFIG_WLAN_VENDOR_INTEL CONFIG_INPUT CONFIG_INPUT_KEYBOARD CONFIG_INPUT_MOUSE CONFIG_HIDRAW CONFIG_SERIO CONFIG_SERIO_I8042 CONFIG_ACPI CONFIG_X86_PLATFORM_DRIVERS_DELL CONFIG_DELL_SMBIOS_WMI CONFIG_DELL_SMBIOS_SMM CONFIG_CPU_FREQ CONFIG_CPU_FREQ_DEFAULT_GOV_SCHEDUTIL CONFIG_CPU_FREQ_GOV_SCHEDUTIL CONFIG_THERMAL CONFIG_ZRAM CONFIG_ZRAM_BACKEND_LZ4 CONFIG_KEYBOARD_ATKBD CONFIG_SOUND CONFIG_SND CONFIG_CPU_FREQ_GOV_USERSPACE CONFIG_HWMON CONFIG_I2C CONFIG_DEBUG_FS CONFIG_ZSMALLOC_STAT CONFIG_ZRAM_BACKEND_LZO CONFIG_ZRAM_BACKEND_LZ4HC CONFIG_ZRAM_BACKEND_ZSTD CONFIG_ZRAM_BACKEND_DEFLATE CONFIG_ZRAM_BACKEND_842 CONFIG_ZRAM_DEF_COMP_LZO CONFIG_ZRAM_WRITEBACK CONFIG_ZRAM_TRACK_ENTRY_ACTIME CONFIG_ZRAM_MEMORY_TRACKING CONFIG_ZRAM_MULTI_COMP; do
    require "$modular" "$key" y
done
for key in CONFIG_ATA_PIIX CONFIG_BLK_DEV_SR CONFIG_SCSI_CDROM CONFIG_BTRFS_FS CONFIG_EXFAT_FS CONFIG_FAT_FS CONFIG_VFAT_FS CONFIG_ISO9660_FS CONFIG_UDF_FS CONFIG_FUSE_FS CONFIG_SQUASHFS CONFIG_SQUASHFS_ZSTD CONFIG_OVERLAY_FS CONFIG_AGP_INTEL CONFIG_DRM_I915 CONFIG_CFG80211 CONFIG_MAC80211 CONFIG_RFKILL CONFIG_IWLEGACY CONFIG_IWL3945 CONFIG_USB CONFIG_USB_EHCI_HCD CONFIG_USB_UHCI_HCD CONFIG_USB_STORAGE CONFIG_USB_HID CONFIG_USB_USBNET CONFIG_USB_NET_CDCETHER CONFIG_USB_NET_RNDIS_HOST CONFIG_USB_NET_CDC_NCM CONFIG_INPUT_EVDEV CONFIG_HID_GENERIC CONFIG_INPUT_JOYSTICK CONFIG_INPUT_JOYDEV CONFIG_INPUT_UINPUT CONFIG_SND_HDA CONFIG_SND_HDA_INTEL CONFIG_SND_HDA_CODEC_SIGMATEL CONFIG_BT CONFIG_BT_HCIBTUSB CONFIG_ACPI_AC CONFIG_ACPI_BATTERY CONFIG_ACPI_BUTTON CONFIG_ACPI_FAN CONFIG_ACPI_THERMAL CONFIG_ACPI_VIDEO CONFIG_DELL_LAPTOP CONFIG_DELL_WMI CONFIG_DELL_PC CONFIG_DELL_SMO8800 CONFIG_CPU_FREQ_GOV_POWERSAVE CONFIG_CPU_FREQ_GOV_ONDEMAND CONFIG_CPU_FREQ_GOV_CONSERVATIVE CONFIG_X86_ACPI_CPUFREQ CONFIG_SENSORS_CORETEMP CONFIG_SENSORS_DELL_SMM CONFIG_I2C_I801 CONFIG_BACKLIGHT_CLASS_DEVICE CONFIG_DRM CONFIG_HID CONFIG_ACPI_WMI CONFIG_DCDBAS CONFIG_DELL_SMBIOS CONFIG_MOUSE_PS2 CONFIG_DELL_WMI_DESCRIPTOR CONFIG_I2C_SMBUS CONFIG_I2C_ALGOBIT; do
    require "$modular" "$key" m
done
for key in CONFIG_MOUSE_PS2_ALPS CONFIG_MOUSE_PS2_SYNAPTICS CONFIG_MOUSE_PS2_TRACKPOINT; do
    require "$modular" "$key" y
done
require "$modular" CONFIG_MODULE_COMPRESS_ALL n
for file in "$modular" "$tiny"; do
    for key in CONFIG_ZRAM_DEF_COMP_LZORLE CONFIG_ZRAM_DEF_COMP_LZ4 CONFIG_ZRAM_DEF_COMP_LZ4HC CONFIG_ZRAM_DEF_COMP_ZSTD CONFIG_ZRAM_DEF_COMP_DEFLATE CONFIG_ZRAM_DEF_COMP_842; do
        require "$file" "$key" n
    done
done

# Known absent D630 hardware: no USB 3 xHCI or NVMe host/fabrics/target.
for key in CONFIG_USB_XHCI_HCD CONFIG_NVME_CORE CONFIG_BLK_DEV_NVME CONFIG_NVME_FABRICS CONFIG_NVME_RDMA CONFIG_NVME_FC CONFIG_NVME_TCP CONFIG_NVME_TARGET; do
    require "$modular" "$key" n
done

# Profile 20 prunes known-absent D630 buses, devices and media families.
for key in CONFIG_USB_XHCI_HCD CONFIG_NVME_CORE CONFIG_BLK_DEV_NVME CONFIG_NVME_FABRICS CONFIG_NVME_RDMA CONFIG_NVME_FC CONFIG_NVME_TCP CONFIG_NVME_TARGET CONFIG_EFI CONFIG_EFI_STUB CONFIG_EFIVAR_FS CONFIG_ETHERNET CONFIG_CAN CONFIG_ISDN CONFIG_INFINIBAND CONFIG_FIREWIRE CONFIG_NFC CONFIG_WIMAX CONFIG_IEEE802154 CONFIG_6LOWPAN CONFIG_USB_GADGET CONFIG_MTD CONFIG_MEDIA_DIGITAL_TV_SUPPORT CONFIG_MEDIA_RADIO_SUPPORT CONFIG_MEDIA_SDR_SUPPORT CONFIG_MEDIA_TEST_SUPPORT CONFIG_DVB_CORE CONFIG_RADIO_ADAPTERS CONFIG_DRM_AMDGPU CONFIG_DRM_RADEON CONFIG_DRM_NOUVEAU; do
    require "$modular" "$key" n
done

# Profile 30: Tiny live kernel.
for key in CONFIG_BLK_DEV_INITRD CONFIG_PROC_FS CONFIG_IKCONFIG CONFIG_IKCONFIG_PROC CONFIG_DEVTMPFS CONFIG_TMPFS CONFIG_SATA_AHCI CONFIG_ATA_PIIX CONFIG_NTFS3_FS CONFIG_EXFAT_FS CONFIG_VFAT_FS CONFIG_DRM_I915 CONFIG_IWL3945 CONFIG_USB_STORAGE CONFIG_USB_NET_RNDIS_HOST CONFIG_SWAP CONFIG_ZRAM CONFIG_ZRAM_BACKEND_LZ4 CONFIG_DEBUG_FS CONFIG_ZSMALLOC_STAT CONFIG_ZRAM_BACKEND_LZO CONFIG_ZRAM_BACKEND_LZ4HC CONFIG_ZRAM_BACKEND_ZSTD CONFIG_ZRAM_BACKEND_DEFLATE CONFIG_ZRAM_BACKEND_842 CONFIG_ZRAM_DEF_COMP_LZO CONFIG_ZRAM_WRITEBACK CONFIG_ZRAM_TRACK_ENTRY_ACTIME CONFIG_ZRAM_MEMORY_TRACKING CONFIG_ZRAM_MULTI_COMP; do
    require "$tiny" "$key" y
done
grep -Fxq 'CONFIG_MODULES=n' "$tiny"
for key in CONFIG_BLK_DEV_LOOP CONFIG_OVERLAY_FS CONFIG_SQUASHFS; do
    require "$tiny" "$key" n
done

# Profile 40: Gentoo live SquashFS kernel.
for key in CONFIG_MODULES CONFIG_PROC_FS CONFIG_IKCONFIG CONFIG_IKCONFIG_PROC CONFIG_BLK_DEV_INITRD CONFIG_BLK_DEV_LOOP CONFIG_OVERLAY_FS CONFIG_SQUASHFS CONFIG_SQUASHFS_ZSTD CONFIG_DEVTMPFS CONFIG_TMPFS CONFIG_SATA_AHCI CONFIG_ATA_PIIX CONFIG_BTRFS_FS CONFIG_NTFS3_FS CONFIG_EXFAT_FS CONFIG_VFAT_FS CONFIG_DRM_I915 CONFIG_IWL3945 CONFIG_USB_STORAGE CONFIG_USB_NET_RNDIS_HOST CONFIG_SND_HDA_INTEL; do
    require "$builtin" "$key" y
done
for key in CONFIG_DEBUG_FS CONFIG_ZSMALLOC_STAT CONFIG_ZRAM_BACKEND_LZO CONFIG_ZRAM_BACKEND_LZ4 CONFIG_ZRAM_BACKEND_LZ4HC CONFIG_ZRAM_BACKEND_ZSTD CONFIG_ZRAM_BACKEND_DEFLATE CONFIG_ZRAM_BACKEND_842 CONFIG_ZRAM_DEF_COMP_LZO CONFIG_ZRAM_WRITEBACK CONFIG_ZRAM_TRACK_ENTRY_ACTIME CONFIG_ZRAM_MEMORY_TRACKING CONFIG_ZRAM_MULTI_COMP; do
    require "$builtin" "$key" y
done
for key in CONFIG_ZRAM_DEF_COMP_LZORLE CONFIG_ZRAM_DEF_COMP_LZ4 CONFIG_ZRAM_DEF_COMP_LZ4HC CONFIG_ZRAM_DEF_COMP_ZSTD CONFIG_ZRAM_DEF_COMP_DEFLATE CONFIG_ZRAM_DEF_COMP_842; do
    require "$builtin" "$key" n
done
grep -Fxq 'CONFIG_DEVTMPFS_MOUNT=n' "$builtin"
grep -Fxq 'CONFIG_LOCALVERSION="-d630-gentoo"' "$builtin"
echo "All three independent D630 kernel profiles passed static policy checks."
